"""The `financial-metrics` CLI: compile the dbt project's saved queries to SQL for the chart boards.

dbt charts runs SQL, not semantic-layer queries, so each saved query (defined in the domain YAML) is
compiled by MetricFlow into DuckDB SQL and written as a named query in `charts/_metrics.yml`. Boards
extend that file and read the metrics as `{{ queries.<saved query> }}`, so a metric has one definition
whichever board shows it.

- `update` rewrites `charts/_metrics.yml` from `target/semantic_manifest.json` (run `dbt parse` first).
- `check` fails if the file is out of date, e.g. after a metric changed without an update.

Run from the dbt project directory. The manifest is read from DBT_TARGET_PATH when set (the image
uses /data/target), else ./target.
"""

import argparse
import json
import os
import sys
from collections.abc import Sequence
from pathlib import Path

OUTPUT = Path("charts") / "_metrics.yml"

HEADER = """\
# GENERATED by `financial-metrics update` (task charts:metrics PROJECT=financial): don't edit.
# One query per saved query in the dbt project, compiled to DuckDB SQL by MetricFlow. Boards extend this
# file and read a saved query's rows as {{ queries.<name> }}. Edit the saved query, then regenerate.
# yamllint disable rule:line-length
"""


def _manifest_path() -> Path:
    return Path(os.environ.get("DBT_TARGET_PATH", "target")) / "semantic_manifest.json"


def _load_manifest(path: Path) -> dict:
    if not path.is_file():
        sys.exit(f"{path} not found: run `dbt parse` first")
    manifest = json.loads(path.read_text())
    # Drop the database from every relation, so the SQL names main.<table> like the boards' own SQL
    # and works whatever the DuckDB file (and so its catalog) is called
    relations = [model["node_relation"] for model in manifest["semantic_models"]]
    relations += [
        spine["node_relation"]
        for spine in manifest["project_configuration"]["time_spines"]
    ]
    for relation in relations:
        relation["database"] = None
        relation["relation_name"] = f'"{relation["schema_name"]}"."{relation["alias"]}"'
    return manifest


def compile_saved_queries(manifest: dict) -> dict[str, tuple[str, str]]:
    """Each saved query's description and DuckDB SQL, by name."""
    # Imported here so the rest of the package doesn't need MetricFlow (it comes with dbt-core)
    from metricflow.engine.metricflow_engine import (
        MetricFlowEngine,
        MetricFlowQueryRequest,
    )
    from metricflow.protocols.sql_client import SqlEngine
    from metricflow.sql.render.duckdb_renderer import DuckDbSqlPlanRenderer
    from metricflow_semantic_interfaces.implementations.semantic_manifest import (
        PydanticSemanticManifest,
    )
    from metricflow_semantic_interfaces.transformations.semantic_manifest_transformer import (
        PydanticSemanticManifestTransformer,
    )
    from metricflow_semantics.model.semantic_manifest_lookup import (
        SemanticManifestLookup,
    )

    class RenderOnlyClient:
        """Enough of a SQL client to render queries; nothing is executed."""

        sql_engine_type = SqlEngine.DUCKDB
        sql_plan_renderer = DuckDbSqlPlanRenderer()

    semantic_manifest = PydanticSemanticManifestTransformer.transform(
        PydanticSemanticManifest.parse_obj(manifest)
    )
    engine = MetricFlowEngine(
        SemanticManifestLookup(semantic_manifest),
        RenderOnlyClient(),  # ty: ignore[invalid-argument-type]
    )
    compiled = {}
    for saved_query in sorted(semantic_manifest.saved_queries, key=lambda q: q.name):
        request = MetricFlowQueryRequest.create(saved_query_name=saved_query.name)
        sql = engine.explain(request).sql_statement.sql
        compiled[saved_query.name] = (saved_query.description or "", sql)
    return compiled


def render(compiled: dict[str, tuple[str, str]]) -> str:
    lines = [HEADER, "queries:"]
    for name, (description, sql) in compiled.items():
        lines += [
            "",
            f"  {name}:",
            f"    notes: {json.dumps(description)}",
            "    sql: |",
        ]
        lines += [f"      {line}".rstrip() for line in sql.strip().splitlines()]
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=["update", "check"])
    args = parser.parse_args(argv)

    expected = render(compile_saved_queries(_load_manifest(_manifest_path())))
    current = OUTPUT.read_text() if OUTPUT.is_file() else ""
    if args.command == "check":
        if current != expected:
            sys.exit(
                f"{OUTPUT} is out of date: run `task charts:metrics PROJECT=financial`"
            )
        print(f"{OUTPUT} is up to date")
        return
    OUTPUT.write_text(expected)
    print(
        f"{'Updated' if current != expected else 'Unchanged'}: {OUTPUT} ({len(expected.splitlines())} lines)"
    )


if __name__ == "__main__":
    main()
